interface GeneratedPage {
  title: string;
  description: string;
  command: string;
  source: string;
  body: string;
}

const TABLE_CELL_PIPE = /\|/gu;
const TABLE_CELL_NEWLINE = /\r?\n/gu;
const BLANK_RUN = /\n{3,}/gu;
const BACKTICK_RUN = /`+/gu;
const CODE_SPAN = /(?<ticks>`+)[\s\S]*?\k<ticks>/gu;
const ANGLE_BRACKET = /[<>]/gu;
const HEADING_LINK = /\[(?<text>[^\]]*)\]\([^)]*\)/gu;
const HEADING_MARKUP = /[*_`~]/gu;
const SLUG_REMOVED = /[^\p{L}\p{M}\p{N}\p{Pc} -]/gu;
const SLUG_SPACE = / /gu;

const ANGLE_ENTITY: Record<string, string> = { "<": "&lt;", ">": "&gt;" };

export const escapeCell = (value: string): string =>
  value.replaceAll(TABLE_CELL_PIPE, "\\|").replaceAll(TABLE_CELL_NEWLINE, " ");

export const code = (value: string): string => {
  const longestRun = Math.max(
    0,
    ...[...value.matchAll(BACKTICK_RUN)].map(([run]) => run.length)
  );

  const fence = "`".repeat(longestRun + 1);
  const padding = value.startsWith("`") || value.endsWith("`") ? " " : "";

  return `${fence}${padding}${value}${padding}${fence}`;
};

const escapeAngles = (value: string): string =>
  value.replaceAll(
    ANGLE_BRACKET,
    (bracket) => ANGLE_ENTITY[bracket] ?? bracket
  );

export const escapeProse = (value: string): string => {
  const spans = [...value.matchAll(CODE_SPAN)];
  const outside = value
    .split(CODE_SPAN)
    .filter((_part, index) => index % 2 === 0);

  return outside
    .map((part, index) => `${escapeAngles(part)}${spans[index]?.[0] ?? ""}`)
    .join("");
};

export const table = (header: string[], rows: string[][]): string =>
  [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((cells) => `| ${cells.join(" | ")} |`),
  ].join("\n");

export const headingSlug = (heading: string): string =>
  heading
    .replaceAll(HEADING_LINK, "$<text>")
    .replaceAll(HEADING_MARKUP, "")
    .trim()
    .toLowerCase()
    .replaceAll(SLUG_REMOVED, "")
    .replaceAll(SLUG_SPACE, "-");

export const generatedPage = ({
  title,
  description,
  command,
  source,
  body,
}: GeneratedPage): string => {
  const page = [
    "---",
    `title: ${title}`,
    `description: ${description}`,
    "---",
    "",
    `This page is generated by ${code(command)} from ${source}. Do not edit it by hand: change the source and run the command again.`,
    "",
    body.trim(),
  ].join("\n");

  return `${page.replaceAll(BLANK_RUN, "\n\n").trimEnd()}\n`;
};

export const formatted = async (
  file: string,
  contents: string
): Promise<string> => {
  const formatter = Bun.spawn(
    ["bun", "x", "oxfmt", `--stdin-filepath=${file}`],
    { stderr: "inherit", stdin: new Blob([contents]), stdout: "pipe" }
  );

  const [output, status] = await Promise.all([
    new Response(formatter.stdout).text(),
    formatter.exited,
  ]);

  if (status !== 0) {
    throw new Error(`oxfmt could not format ${file} (exit ${status}).`);
  }

  return output;
};
